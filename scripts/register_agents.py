"""Register the four factory agents and write agent_config.yaml in one shot.

Needs one BAND *user* key (band_u_...) from app.band.ai, in BAND_API_KEY.
Beats clicking through four dialogs and copying four API keys that each display once.

    BAND_API_KEY=band_u_... .venv/bin/python scripts/register_agents.py
"""

from __future__ import annotations

import asyncio
import os
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from dotenv import load_dotenv  # noqa: E402

from factory.roles import ROLES  # noqa: E402

OUT = Path(__file__).resolve().parent.parent / "agent_config.yaml"

DESCRIPTIONS = {
    "architect": "Turns a spec into an executable plan with objectively checkable acceptance criteria.",
    "builder": "Implements the plan in the repository. Answers verifier findings specifically.",
    "verifier": "Runs checks against each acceptance criterion and produces real evidence or findings.",
    "gatekeeper": "Rules SHIP or BLOCKED on the verifier's evidence. Blocks when evidence is absent.",
}


async def main() -> int:
    load_dotenv()
    key = os.environ.get("BAND_API_KEY")
    if not key:
        print("BAND_API_KEY not set (need a band_u_... user key from app.band.ai)", file=sys.stderr)
        return 2
    if OUT.exists() and os.environ.get("FORCE") != "1":
        print(f"{OUT} exists; re-run with FORCE=1 to overwrite", file=sys.stderr)
        return 2
    if OUT.is_dir():
        print(f"{OUT} is a directory (Docker bind-mount artifact); rm -rf it first", file=sys.stderr)
        return 2

    from band_rest import AsyncRestClient
    from band_rest.types import AgentRegisterRequest

    base = os.environ.get("BAND_REST_URL", "https://app.band.ai")
    client = AsyncRestClient(base_url=base, api_key=key)

    lines: list[str] = ["# Generated by scripts/register_agents.py -- gitignored, keys shown once.\n"]
    ids: list[str] = []
    for role in (ROLES[k] for k in ("architect", "builder", "verifier", "gatekeeper")):
        resp = await client.human_api_agents.register_my_agent(
            agent=AgentRegisterRequest(name=role.name, description=DESCRIPTIONS[role.key])
        )
        agent_id = resp.data.agent.id
        api_key = resp.data.credentials.api_key
        ids.append(agent_id)
        lines.append(f"{role.key}:\n  agent_id: {agent_id!r}\n  api_key: {api_key!r}\n")
        print(f"  registered {role.name}: {agent_id}")

    OUT.write_text("\n".join(lines))
    (OUT.parent / ".agent_ids.txt").write_text("\n".join(ids) + "\n")
    print(f"\nwrote {OUT}")
    print("Next: create a room at app.band.ai, add all four agents, mention @Architect.")
    return 0


if __name__ == "__main__":
    raise SystemExit(asyncio.run(main()))
